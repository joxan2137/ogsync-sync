// Embeds the built Studio plugin (dist/OGSync.rbxm) into the daemon source as
// base64 so `bun build --compile` ships it inside the binary; the daemon writes
// it into the Studio plugins dir on start.
//
// Build order:  bun run build:plugin -> bun run build:embed -> bun run build:bin
//
// This OVERWRITES server/src/update/plugin-blob.ts in place. The committed
// version of that file is a stub whose getPluginBytes() returns null, and the
// generated blob must never be committed — after building locally, restore it:
//
//   git checkout -- server/src/update/plugin-blob.ts
//
// The release workflow regenerates the blob on every run, so a committed stub
// costs nothing.

import { mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const RBXM = resolve(ROOT, "dist/OGSync.rbxm");
const BLOB = resolve(ROOT, "server/src/update/plugin-blob.ts");

const rbxm = Bun.file(RBXM);
if (!(await rbxm.exists())) {
  console.error(
    "embed-plugin: dist/OGSync.rbxm not found — build the plugin first:\n" +
      "  rokit install && bun run build:plugin",
  );
  process.exit(1);
}

const b64 = Buffer.from(await rbxm.arrayBuffer()).toString("base64");

await mkdir(dirname(BLOB), { recursive: true });
await Bun.write(
  BLOB,
  `// GENERATED by scripts/embed-plugin.ts — do not edit, do not commit.
// Restore the committed stub after a local build:
//   git checkout -- server/src/update/plugin-blob.ts
const B64 = ${JSON.stringify(b64)};

export async function getPluginBytes(): Promise<Uint8Array | null> {
  return Uint8Array.from(atob(B64), (c) => c.charCodeAt(0));
}
`,
);

console.log(`embed-plugin: ${rbxm.size} rbxm bytes -> ${b64.length} base64 chars -> server/src/update/plugin-blob.ts`);
if (!process.env.CI) {
  console.log("reminder: `git checkout -- server/src/update/plugin-blob.ts` once you are done building");
}
