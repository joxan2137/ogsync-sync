// Stamps package.json's version into the two generated version files so the
// daemon and the plugin always report the same string (the handshake rejects a
// mismatch — see docs/DESIGN.md "Version lockstep"):
//
//   server/src/version.ts      export const VERSION
//   plugin/src/Version.luau    return "<version>"
//
// Idempotent: rewrites a file only when its content differs.

import { resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;

async function packageVersion(): Promise<string> {
  const pkg = (await Bun.file(resolve(ROOT, "package.json")).json()) as { version?: unknown };
  if (typeof pkg.version !== "string" || !SEMVER.test(pkg.version)) {
    throw new Error(`package.json version is not a semver string: ${JSON.stringify(pkg.version)}`);
  }
  return pkg.version;
}

async function writeIfChanged(relPath: string, content: string): Promise<void> {
  const file = Bun.file(resolve(ROOT, relPath));
  if ((await file.exists()) && (await file.text()) === content) {
    console.log(`  unchanged ${relPath}`);
    return;
  }
  await Bun.write(file, content);
  console.log(`  wrote     ${relPath}`);
}

const version = await packageVersion();
console.log(`stamp-version: ${version}`);

await writeIfChanged(
  "server/src/version.ts",
  `// GENERATED by scripts/stamp-version.ts — do not edit.
export const VERSION = ${JSON.stringify(version)};
`,
);

await writeIfChanged(
  "plugin/src/Version.luau",
  `--!strict
-- GENERATED by scripts/stamp-version.ts — do not edit.
return ${JSON.stringify(version)}
`,
);
